#include <bits/stdc++.h>

using namespace std;

int main() {
    ios_base::sync_with_stdio(false);
    cin.tie(nullptr);

    int t;
    cin >> t;

    while(t != 0) {
        string a, b, c;
        cin >> a >> b >> c;

        cout << a[0] << b[0] << c[0] << "\n";
        
        t--;
    }

    return 0;
}